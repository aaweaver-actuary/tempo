"""Domain capabilities borrowing the transaction; no SQL or generic unit of work."""
from typing import Protocol
from .models import (AttemptReceipt, CardFacts, ContinuationFacts, PreparedNext,
                     QueueAttempt, ReviewCommand, ReviewContext, ReviewPolicy)


class ReviewStore(Protocol):
    def is_deleted(self, card_id: str) -> bool: ...
    def receipt(self, attempt_id: str) -> AttemptReceipt | None: ...
    def card(self, card_id: str) -> CardFacts | None: ...
    def find_attempt(self, command: ReviewCommand, context: ReviewContext) -> QueueAttempt | None: ...
    def recover_attempt(self, command: ReviewCommand) -> QueueAttempt: ...
    def latest_review_id(self, card_id: str, *, valid_only: bool) -> int: ...
    def current_revision(self, card_id: str) -> int | None: ...
    def policy(self) -> ReviewPolicy: ...
    def retain_introduction(self, card_id: str, queue_day: str) -> None: ...
    def has_later_review(self, card_id: str, context: ReviewContext) -> bool: ...
    def reconcile_completed(self, command: ReviewCommand, attempt: QueueAttempt,
                            context: ReviewContext, *, guided: bool, revision: int | None,
                            competing_review: dict | None = None) -> dict: ...
    def bind_receipt(self, command: ReviewCommand, request_json: str, *, restore_original=False) -> None: ...
    def schedule_snapshot(self, card_id: str) -> dict | None: ...
    def schedule(self, command: ReviewCommand, context: ReviewContext, *, outcome: str,
                 guided: bool, policy: ReviewPolicy) -> dict: ...
    def complete_attempt(self, command: ReviewCommand, context: ReviewContext, *, guided: bool) -> None: ...
    def mark_clean_tactic(self, card_id: str, context: ReviewContext) -> None: ...
    def requeue(self, attempt: QueueAttempt, card_id: str, after: int | None, state: str) -> int | None: ...
    def save_snapshot(self, review_id: int, snapshot: dict) -> None: ...
    def save_receipt(self, command: ReviewCommand, context: ReviewContext, result: dict) -> None: ...
    def retain_completion(self, command: ReviewCommand, attempt: QueueAttempt, result_json: str, *, origin_only=False) -> None: ...
    def refresh_progression(self, context: ReviewContext, card: CardFacts, result: dict) -> None: ...
    def refresh_priority(self, repertoire_id: str, *, transactional_only=False) -> None: ...
    def refresh_maturity(self, context: ReviewContext) -> None: ...


class ReviewSubmissionStore(ReviewStore, Protocol):
    def lock_review_cards(self, command: ReviewCommand) -> bool: ...
    def lock_queue_date(self) -> None: ...
    def completed_evidence_exists(self, attempt_id: str) -> bool: ...
    def evidence_revision_allowed(self, command: ReviewCommand) -> bool: ...
    def persist_evidence(self, command: ReviewCommand) -> None: ...
    def complete_evidence(self, command: ReviewCommand, result: dict) -> None: ...
    def inherit_evidence_scope(self, command: ReviewCommand, result: dict) -> None: ...
    def continuation_facts(self, candidate: PreparedNext) -> ContinuationFacts | None: ...
    def issue_head(self, candidate: PreparedNext) -> bool: ...
    def save_continuation(self, attempt_id: str, result: dict) -> None: ...

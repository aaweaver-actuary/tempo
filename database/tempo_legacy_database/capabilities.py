"""Static capabilities of the legacy SQLite/PostgreSQL connection scopes.

These protocols describe the common consumer operations, not SQL permissions.
The connection context remains responsible for transaction and resource lifetime.
"""
from collections.abc import Iterator, Sequence
from typing import Protocol, overload


class Row(Protocol):
    @overload
    def __getitem__(self, key: int) -> object: ...
    @overload
    def __getitem__(self, key: str) -> object: ...
    def __iter__(self) -> Iterator[object]: ...
    def __len__(self) -> int: ...
    def keys(self) -> Sequence[str]: ...


class Cursor(Protocol):
    def fetchone(self) -> Row | None: ...
    def fetchall(self) -> Sequence[Row]: ...
    def __iter__(self) -> Iterator[Row]: ...


class ReadConnection(Protocol):
    def execute(self, statement: str, parameters: tuple[object, ...] | list[object] = ()) -> Cursor: ...


class BorrowedTransaction(ReadConnection, Protocol):
    """Operations inside a caller-owned scope; no commit or close authority."""
    @property
    def in_transaction(self) -> bool: ...
    def executemany(self, statement: str, parameters: list[tuple[object, ...]] | tuple[tuple[object, ...], ...]) -> Cursor: ...

    RETURN NEW;
END $$;
CREATE TRIGGER opening_evidence_edited_scope AFTER UPDATE OF revision,start_fen,moves_json,trained_color,content_type ON cards
    FOR EACH ROW EXECUTE FUNCTION opening_evidence_capture_edited_scope();
